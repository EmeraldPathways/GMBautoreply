CREATE TABLE IF NOT EXISTS settings (id INTEGER PRIMARY KEY CHECK(id=1), data TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS secrets (name TEXT PRIMARY KEY, value TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS oauth_states (state TEXT PRIMARY KEY, verifier TEXT NOT NULL, session_id TEXT NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS sessions (id TEXT PRIMARY KEY, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS locations (name TEXT PRIMARY KEY, title TEXT NOT NULL, account TEXT NOT NULL, enabled INTEGER NOT NULL DEFAULT 1, seen INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS reviews (
  id TEXT PRIMARY KEY, name TEXT NOT NULL, rating INTEGER NOT NULL, text TEXT NOT NULL,
  draft TEXT NOT NULL DEFAULT '', status TEXT NOT NULL DEFAULT 'new', demo INTEGER NOT NULL DEFAULT 0,
  updated TEXT NOT NULL DEFAULT '', location TEXT NOT NULL DEFAULT '', created TEXT NOT NULL DEFAULT '',
  first_seen INTEGER NOT NULL, published_at TEXT NOT NULL DEFAULT '', flag TEXT NOT NULL DEFAULT '',
  theme TEXT NOT NULL DEFAULT '', source TEXT NOT NULL DEFAULT '', processing_at INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX IF NOT EXISTS reviews_due ON reviews(status, demo, first_seen);
CREATE TABLE IF NOT EXISTS examples (id INTEGER PRIMARY KEY AUTOINCREMENT, review_id TEXT UNIQUE, original TEXT NOT NULL DEFAULT '', reply TEXT NOT NULL, location TEXT NOT NULL DEFAULT '', created INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS audit (ts INTEGER NOT NULL, action TEXT NOT NULL, review TEXT NOT NULL DEFAULT '', detail TEXT NOT NULL DEFAULT '');
CREATE INDEX IF NOT EXISTS audit_recent ON audit(ts DESC);
CREATE TABLE IF NOT EXISTS login_attempts (key TEXT PRIMARY KEY, count INTEGER NOT NULL, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS daily_budget (day TEXT PRIMARY KEY, used INTEGER NOT NULL);
